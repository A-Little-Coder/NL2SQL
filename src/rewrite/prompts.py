# ============================================================================
# Rewrite 子图的 Prompt 模板（v2 设计）
# ============================================================================
# 两个独立的 Prompt：
#   1. DETECT_ISSUES_PROMPT — 检测指代/歧义/对象缺失
#   2. REWRITE_EXECUTE_PROMPT — 利用上下文改写 query
# ============================================================================

from langchain_core.prompts import ChatPromptTemplate


# ---------------------------------------------------------------------------
# 问题检测：检测指代/歧义/对象缺失
# ---------------------------------------------------------------------------
DETECT_ISSUES_PROMPT = ChatPromptTemplate.from_messages([
    ("system", "你是数据库查询分析专家，负责检测用户查询中是否存在指代、歧义、对象缺失，只输出 JSON。"),
    ("user", """分析用户查询，检测是否存在以下问题：

## 检测项

### 指代
- 查询含代词（它、那、其、该、此等，如"它的销售额"、"那去年的呢"）
- 查询含省略成分（如"只看北京的呢"、"那最高的呢"）

### 歧义
- 查询含多义实体（如"苹果"可指公司或水果）
- 查询含常见简称（如"加州"="加利福尼亚州"、"京"="北京"等，**这些不算歧义**）

### 缺失
- 查询缺少关键限定（如"查销售额"缺公司/时间，但历史上下文可能补全）

## 判定规则
- 如果查询语义完整、意图清晰，即使有常见简称，也判 has_issues=false
- 如果查询含指代/歧义/缺失，且历史上下文可能补全，判 has_issues=true
- 如果查询明显不含任何查询意图（纯感叹词、无意义字符），判 has_issues=true

## 会话历史（最近对话，最多前 5 轮）
{history_lines}

## 当前用户查询
{user_query}

请返回 JSON：
{{
  "has_issues": true | false,
  "issue_types": ["指代" | "歧义" | "缺失"] | [],
  "issue_detail": "问题描述，无问题则填空字符串",
  "original_query": "原始查询"
}}"""),
])


# ---------------------------------------------------------------------------
# 改写执行：利用上下文改写 query
# ---------------------------------------------------------------------------
REWRITE_EXECUTE_PROMPT = ChatPromptTemplate.from_messages([
    ("system", "你是数据库查询改写专家，负责补全用户查询中的指代、歧义、缺失信息，只输出 JSON。"),
    ("user", """根据会话历史和用户补充信息（如有），改写用户查询为完整语义的查询语句。

## 改写规则
1. 保持原意，只补全缺失信息，不改变用户原本的意图
2. 利用会话历史补全指代/歧义/缺失
3. 如果有用户补充信息（clarify_context），优先使用它来补全

## 会话历史（最近对话，最多前 5 轮）
{history_lines}

## 用户补充信息（如有，表示用户对上一轮反问的回答）
{clarify_context}

## 当前用户查询
{user_query}

请返回 JSON：
{{
  "rewritten_query": "改写后的完整语义查询",
  "rewrite_reason": "改写说明（简短，中文，说明改了什么）"
}}"""),
])


# ---------------------------------------------------------------------------
# 前置拒答：LLM 语义判定增删改 / 危险信息 / 正常（D9）
# ---------------------------------------------------------------------------
PRE_REJECT_PROMPT = ChatPromptTemplate.from_messages([
    ("system", "你是数据库查询安全审核专家，负责判定用户查询是否属于写操作或危险信息指令，只输出 JSON。"),
    ("user", """判定用户查询属于以下哪一类：

## 类别

### write_op（增删改意图）
- 任何修改/写入/删除/创建/清空数据的意图，包括换皮说法
- 示例："删除学生表里所有数据"、"把这条记录改一下"、"清空上周的订单"、"给用户表加一列"、"删掉那批"、"把学生表导出来后改"

### dangerous_info（危险信息指令）
- 刺探系统表/元数据（information_schema、pg_catalog、sys 表、表结构枚举）
- 批量导出/ dump 敏感字段（密码、token、身份证、手机号等整列导出）
- 越权探查 / 注入式 / 非业务查询
- 示例："列出所有用户的密码"、"导出整张学生表"、"显示 information_schema 的表"、"把全表数据 dump 出来"

### normal（正常查询）
- 普通统计分析/查询，即使含"更新时间"等字段名也算正常
- 示例："查询洛杉矶县的特许学校数量"、"统计每个学生的更新时间"、"那它们的平均学生人数呢"

## 判定规则
- 只有明确的写操作或危险信息意图才 reject=true
- 含"更新"/"修改"等词但作为字段名或查询语境的，判 normal
- 模糊时倾向 normal（宁放行不误杀）

## 当前用户查询
{user_query}

请返回 JSON：
{{
  "reject": true | false,
  "category": "write_op" | "dangerous_info" | "normal",
  "reason": "判定原因（简短，中文；normal 时填"正常查询"）"
}}"""),
])