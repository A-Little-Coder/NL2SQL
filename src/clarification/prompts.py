from langchain_core.prompts import ChatPromptTemplate


# ---------------------------------------------------------------------------
# TaskDecomposer：意图拆解（EXECUTE 单意图/多意图）
# ---------------------------------------------------------------------------
TASK_DECOMPOSER_PROMPT = ChatPromptTemplate.from_messages([
    ("system", "你是数据库查询意图理解专家，只输出 JSON。"),
    ("user", """分析用户的查询，判断是单意图还是多意图。

裁决规则：

### EXECUTE（执行）
- **单意图**：一句话只问一件事 → intent_type="single"，subqueries 长度为 1
- **多意图**：一句话含多个独立查询意图 → intent_type="multi"，分解为多个子查询
  - 例："查询苹果的销售额和利润" → ["查询苹果的销售额", "查询苹果的利润"]
  - 例："查询销售额，再对比去年" → ["查询销售额", "对比销售额与去年同期"]
  - **保持语义完整**：不要把一个完整意图拆碎（如"各科成绩"不拆成"各科"+"成绩"）

## 用户查询
{user_query}

## 数据库范围（仅参考，可能为空）
{db_id}

请返回 JSON：
{{
  "verdict": "execute",
  "intent_type": "single" | "multi",
  "subqueries": ["子查询1", "子查询2"],
  "reason": "裁决理由（简短）"
}}"""),
])


# ---------------------------------------------------------------------------
# ResultSummarizer：多子查询结果汇总（决策 15）
# ---------------------------------------------------------------------------
# 注：输入只含"结构摘要"（列名+行数+前5行），不含原始整表，节约 token
RESULT_SUMMARIZER_PROMPT = ChatPromptTemplate.from_messages([
    ("system", "你是数据查询结果汇总专家，用中文输出一段连贯的自然语言回答。"),
    ("user", """用户提出了一个问题，系统分解为多个子查询并各自执行。请把各子查询结果汇总成一段连贯的中文回答。

## 汇总要求
1. 按子查询顺序组织，每个子结果标注其来源（"子查询 N：..."）
2. 提炼关键数字和结论，不要逐行罗列数据
3. 如果某个子查询失败，如实说明该部分无法获取
4. 语言自然、口语化，适合直接给用户看

## 用户原始问题
{user_query}

## 各子查询结果摘要（列名 + 行数 + 前 5 行样本）
{subquery_summaries}

请直接输出汇总回答（纯文本，不要 JSON，不要前置说明）："""),
])